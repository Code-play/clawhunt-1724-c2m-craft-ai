"""Cultural IP pipeline: character bible, visual library, short drama, reel and licensing."""

from __future__ import annotations

from . import bible as bible_mod
from . import drama as drama_mod
from . import licensing as licensing_mod
from . import reel as reel_mod
from . import reviews as reviews_mod
from . import visuals as visuals_mod


class IpPipeline:
    def __init__(self, store, settings) -> None:
        self.store = store
        self.settings = settings
        self.reviews = reviews_mod.build(store, settings)
        self.bible = bible_mod.build(store, settings, self.reviews)
        self.assets = visuals_mod.build(store, settings, self.bible)
        self.drama = drama_mod.build(store, settings, self.reviews)
        self.merch_specs = licensing_mod.build_merch_specs(store, settings, self.reviews)
        self.license = licensing_mod.build_license(
            store, settings, self.bible, self.reviews, self.merch_specs
        )

    # -- views -----------------------------------------------------------
    def asset(self, asset_id: str) -> dict:
        return visuals_mod.by_id(self.assets, asset_id)

    def review_for(self, kind: str, ref: str) -> dict | None:
        return reviews_mod.for_subject(self.reviews, kind, ref)

    def reel_html(self) -> str:
        return reel_mod.render(
            self.drama,
            self.assets,
            self.bible,
            generated_note="Generated by python -m c2m_craft demo from the cultural IP configuration.",
        )

    def report(self) -> dict:
        summary = {
            "characters": len(self.bible["canon"]["characters"]),
            "assets": len(self.assets),
            "asset_kinds": visuals_mod.summary(self.assets)["by_kind"],
            "scenes": drama_mod.summary(self.drama)["scenes"],
            "frames": drama_mod.summary(self.drama)["frames"],
            "reel_seconds": drama_mod.summary(self.drama)["total_seconds"],
            "licence_documents": licensing_mod.document_summary(self.license)["documents"],
            "merch_specs": len(self.merch_specs),
            "reviews": len(self.reviews),
            "heritage_refs": len(self.bible["heritage_refs"]),
        }
        return {
            "version": "1.0.0",
            "bible": self.bible,
            "assets": self.assets,
            "asset_summary": visuals_mod.summary(self.assets),
            "drama": self.drama,
            "drama_summary": drama_mod.summary(self.drama),
            "license": self.license,
            "license_summary": licensing_mod.document_summary(self.license),
            "merch_specs": self.merch_specs,
            "merch_summary": licensing_mod.merch_summary(self.merch_specs),
            "reviews": [self.reviews[key] for key in sorted(self.reviews)],
            "summary": summary,
        }

    def describe(self) -> dict:
        return {
            "bible": self.bible,
            "asset_summary": visuals_mod.summary(self.assets),
            "assets": self.assets,
            "drama": self.drama,
            "license": self.license,
            "merch_specs": self.merch_specs,
            "reviews": [self.reviews[key] for key in sorted(self.reviews)],
            "reel": {"path": "/reel", "seconds": self.drama["cut"]["total_seconds"]},
        }
